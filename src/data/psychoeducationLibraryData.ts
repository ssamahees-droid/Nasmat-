// Helper functions for easy querying and filtering
export function getPsychoeducationTracks(): PsychoeducationTrack[] {
  return PSYCHOEDUCATION_TRACKS;
}

export function getPsychoeducationTopics(): PsychoeducationTopic[] {
  return PSYCHOEDUCATION_TOPICS;
}

export function getTopicsByTrack(trackId: string): PsychoeducationTopic[] {
  return PSYCHOEDUCATION_TOPICS.filter(t => t.trackId === trackId);
}

export function getTopicById(topicId: string): PsychoeducationTopic | undefined {
  return PSYCHOEDUCATION_TOPICS.find(t => t.id === topicId);
}

export function searchPsychoeducationTopics(query: string, trackId?: string): PsychoeducationTopic[] {
  const q = query.trim().toLowerCase();
  return PSYCHOEDUCATION_TOPICS.filter(topic => {
    if (trackId && trackId !== 'all' && topic.trackId !== trackId) {
      return false;
    }
    if (!q) return true;
    return (
      topic.title.toLowerCase().includes(q) ||
      topic.subtitle.toLowerCase().includes(q) ||
      topic.introduction.toLowerCase().includes(q) ||
      topic.scientificExplanation.summary.toLowerCase().includes(q) ||
      topic.tags.some(tag => tag.toLowerCase().includes(q))
    );
  });
}
